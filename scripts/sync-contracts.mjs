// Copies what the client needs from the contracts repository (LENS_CONTRACTS_DIR, default ../lens-monad-protocol):
// the ABIs of the contracts it calls or indexes, as `as const` TypeScript for viem's type inference, and the address
// books the deployment scripts write to deployments/<chainId>.json. Then generates
// packages/protocol/src/address-books.ts, which imports every address book in packages/protocol/deployments.
//
// `--address-books` only regenerates address-books.ts, e.g. after dropping a <chainId>.json in
// packages/protocol/deployments by hand: `pnpm sync:contracts --address-books`.
//
// `--mirror` copies what mirror mode reads (README, Mirror mode) instead: the ABIs of the importers, and the address
// books of a migration-mode deployment (lens-monad-protocol's MIGRATION.md), to packages/protocol/deployments/mirror.
// Each mode copies only its own: the importers' ABIs change with the migration's revisions, so a launch checkout never
// overwrites them, and a mirror never passes for a launch deployment.

import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const contractsDir = path.resolve(root, process.env.LENS_CONTRACTS_DIR ?? '../lens-monad-protocol');
const protocolDir = path.join(root, 'packages/protocol');
const booksDir = path.join(protocolDir, 'deployments');
const mirrorBooksDir = path.join(booksDir, 'mirror');

const CONTRACTS = [
  'Account',
  'AccountBlockingRule',
  'AccountFactory',
  'Feed',
  'Graph',
  'LensFactory',
  'Namespace',
  'SponsorRouter',
];

// The importers mirror mode indexes, as of lens-monad-protocol's PR #8 (feat/migration-cutover).
const MIGRATION_CONTRACTS = [
  'MigrationAccount',
  'MigrationAccountBlockingRule',
  'MigrationAccountDeployer',
  'MigrationFeed',
  'MigrationGraph',
  'MigrationNamespace',
];

const ADDRESS_BOOK = /^(\d+)\.json$/;

function constName(name) {
  return `${name[0].toLowerCase()}${name.slice(1)}Abi`;
}

function syncAbis(names) {
  const abisDir = path.join(protocolDir, 'src/abis');
  fs.mkdirSync(abisDir, { recursive: true });
  const source = (name) => path.join(contractsDir, 'ABIs', `${name}.abi.json`);
  const missing = names.filter((name) => !fs.existsSync(source(name)));
  if (missing.length > 0) {
    console.error(
      `No ${missing.map((name) => `ABIs/${name}.abi.json`).join(', ')} in ${contractsDir}.` +
        (missing.some((name) => MIGRATION_CONTRACTS.includes(name))
          ? " A mirror needs lens-monad-protocol's importers: PR #8 or later."
          : '')
    );
    process.exit(1);
  }
  for (const name of names) {
    const abi = JSON.parse(fs.readFileSync(source(name), 'utf-8'));
    fs.writeFileSync(
      path.join(abisDir, `${name}.ts`),
      `// Generated by scripts/sync-contracts.mjs from ABIs/${name}.abi.json. Do not edit.\n` +
        `export const ${constName(name)} = ${JSON.stringify(abi, null, 2)} as const;\n`
    );
  }
  const exports = [...CONTRACTS, ...MIGRATION_CONTRACTS]
    .filter((name) => fs.existsSync(path.join(abisDir, `${name}.ts`)))
    .map((name) => `export { ${constName(name)} } from './${name}';`);
  fs.writeFileSync(
    path.join(abisDir, 'index.ts'),
    `// Generated by scripts/sync-contracts.mjs. Do not edit.\n${exports.join('\n')}\n`
  );
  return names.length;
}

/** A migration-mode deployment's book lists the account importer's deployer. */
function isMirrorBook(book) {
  return book.MigrationAccountDeployer !== undefined;
}

function copyAddressBooks(mirror) {
  const deploymentsDir = path.join(contractsDir, 'deployments');
  const books = fs
    .readdirSync(deploymentsDir)
    .filter((file) => ADDRESS_BOOK.test(file))
    .filter(
      (file) =>
        isMirrorBook(JSON.parse(fs.readFileSync(path.join(deploymentsDir, file), 'utf-8'))) ===
        mirror
    );
  const target = mirror ? mirrorBooksDir : booksDir;
  fs.mkdirSync(target, { recursive: true });
  for (const book of books) {
    fs.copyFileSync(path.join(deploymentsDir, book), path.join(target, book));
  }
  return books.length;
}

/** The chain ids of a directory's address books, each checked against the chain its file is named after. */
function chainIdsIn(dir, label) {
  const chainIds = fs
    .readdirSync(dir)
    .map((file) => ADDRESS_BOOK.exec(file)?.[1])
    .filter(Boolean)
    .map(Number)
    .sort((a, b) => a - b);
  for (const chainId of chainIds) {
    const book = JSON.parse(fs.readFileSync(path.join(dir, `${chainId}.json`), 'utf-8'));
    if (book.chainId !== chainId) {
      console.error(`${label}/${chainId}.json is the address book of chain ${book.chainId}`);
      process.exit(1);
    }
  }
  return chainIds;
}

/** Bundlers need static imports, so the address books are imported one by one, in a generated module. */
function generateAddressBooks() {
  const chainIds = chainIdsIn(booksDir, 'deployments');
  const mirrorChainIds = fs.existsSync(mirrorBooksDir)
    ? chainIdsIn(mirrorBooksDir, 'deployments/mirror')
    : [];
  const imports = [
    ...chainIds.map((id) => `import chain${id} from '../deployments/${id}.json';`),
    ...mirrorChainIds.map((id) => `import mirror${id} from '../deployments/mirror/${id}.json';`),
  ];
  fs.writeFileSync(
    path.join(protocolDir, 'src/address-books.ts'),
    '// Generated by scripts/sync-contracts.mjs from packages/protocol/deployments. Do not edit.\n' +
      `${imports.join('\n')}\n\n` +
      `export const ADDRESS_BOOKS = [${chainIds.map((id) => `chain${id}`).join(', ')}];\n` +
      `export const MIRROR_ADDRESS_BOOKS = [${mirrorChainIds.map((id) => `mirror${id}`).join(', ')}];\n`
  );
  return { chainIds, mirrorChainIds };
}

function describe({ chainIds, mirrorChainIds }) {
  return (
    `address books for chain(s) ${chainIds.join(', ')}` +
    (mirrorChainIds.length ? `, mirrors for chain(s) ${mirrorChainIds.join(', ')}` : '')
  );
}

if (process.argv.includes('--address-books')) {
  console.log(`Generated address-books.ts: ${describe(generateAddressBooks())}`);
} else {
  if (!fs.existsSync(path.join(contractsDir, 'ABIs'))) {
    console.error(
      `No ABIs/ in ${contractsDir}. Set LENS_CONTRACTS_DIR to the lens-monad-protocol checkout.`
    );
    process.exit(1);
  }
  const mirror = process.argv.includes('--mirror');
  const abis = syncAbis(mirror ? MIGRATION_CONTRACTS : CONTRACTS);
  const copied = copyAddressBooks(mirror);
  console.log(
    `Synced ${abis} ABIs and ${copied} ${mirror ? 'mirror ' : ''}address book(s) from ${contractsDir}; ` +
      describe(generateAddressBooks())
  );
}
