// Builds Parallax's own contracts (contracts/, with Foundry) and writes what the client needs from them, as `as const`
// TypeScript for viem's type inference:
//
//   packages/protocol/src/media-store-artifact.ts     MediaStore's ABI, and its init code, which its CREATE2 address
//                                                     derives from
//   packages/protocol/src/club-forwarder-artifact.ts  ClubForwarder's ABI and bytecode, which each community deploys
//
// The artifacts are committed, so only changing a contract needs Foundry.
//
//   pnpm build:contracts

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const contractsDir = path.join(root, 'contracts');

execFileSync('forge', ['build', '--root', contractsDir], { stdio: 'inherit' });

function writeArtifact(contract, file, abiName, bytecodeName) {
  const { abi, bytecode } = JSON.parse(
    fs.readFileSync(path.join(contractsDir, `out/${contract}.sol/${contract}.json`), 'utf-8')
  );
  fs.writeFileSync(
    path.join(root, 'packages/protocol/src', file),
    `// Generated by scripts/build-contracts.mjs from contracts/src/${contract}.sol. Do not edit.\n` +
      `export const ${abiName} = ${JSON.stringify(abi, null, 2)} as const;\n\n` +
      `export const ${bytecodeName} = '${bytecode.object}' as const;\n`
  );
  console.log(`Wrote packages/protocol/src/${file}`);
}

writeArtifact('MediaStore', 'media-store-artifact.ts', 'mediaStoreAbi', 'MEDIA_STORE_INIT_CODE');
writeArtifact(
  'ClubForwarder',
  'club-forwarder-artifact.ts',
  'clubForwarderAbi',
  'CLUB_FORWARDER_BYTECODE'
);
