// Builds Parallax's own contracts (contracts/, with Foundry) and writes what the client needs from them to
// packages/protocol/src/media-store-artifact.ts: MediaStore's ABI, as `as const` TypeScript for viem's type inference,
// and its init code, which its CREATE2 address derives from. The artifact is committed, so only changing the contract
// needs Foundry.
//
//   pnpm build:contracts

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const contractsDir = path.join(root, 'contracts');

execFileSync('forge', ['build', '--root', contractsDir], { stdio: 'inherit' });
const { abi, bytecode } = JSON.parse(
  fs.readFileSync(path.join(contractsDir, 'out/MediaStore.sol/MediaStore.json'), 'utf-8')
);
fs.writeFileSync(
  path.join(root, 'packages/protocol/src/media-store-artifact.ts'),
  '// Generated by scripts/build-contracts.mjs from contracts/src/MediaStore.sol. Do not edit.\n' +
    `export const mediaStoreAbi = ${JSON.stringify(abi, null, 2)} as const;\n\n` +
    `export const MEDIA_STORE_INIT_CODE = '${bytecode.object}' as const;\n`
);
console.log('Wrote packages/protocol/src/media-store-artifact.ts');
